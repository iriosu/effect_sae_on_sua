"""Assemble the manuscript's application-choices and admission-score tables.

Run after regenerating lottery_scores_horizons.tex or
lottery_application_scores.tex. Source tables stay intact. Assignment by track
is included separately through the original lottery_admission_tracks wrapper.
Usage: python3 merge_admission_tables.py "/path/to/Initial submission"
Only presentation changes: all existing estimates, standard errors and stars
are copied verbatim; each panel retains its sample definition and size.
Matches the October 28 afternoon manuscript: cutoff rows remain commented
out, not an active third panel. See Reviews/handoff_mechanisms_2026-10-28.md.
"""
from pathlib import Path
import sys

root = Path(sys.argv[1]).resolve()
tables = root / "tables"
scores = (tables / "lottery_scores_horizons.tex").read_text()
applications = (tables / "lottery_application_scores.tex").read_text()
provenance = "% Generated by code/finalized_design_v1/section6/merge_admission_tables.py."


def between(text, start, end):
    assert text.count(start) == 1 and text.count(end) == 1
    return text.split(start, 1)[1].split(end, 1)[0]


def data_rows(text):
    return [line for line in text.splitlines()
            if "&" in line and not line.startswith(r"\multicolumn")
            and not line.startswith("$N$")]


def panel(title, rows, columns=5):
    return [r"\midrule", rf"\multicolumn{{{columns}}}{{l}}{{\textit{{{title}}}}}\\"] + rows


def write(name, lines):
    (tables / name).write_text("\n".join(lines) + "\n")


score_rows = data_rows(between(scores, r"\midrule", r"\bottomrule"))
list_rows = data_rows(between(applications, r"\textit{Panel A. The application list}}\\",
                             r"\textit{Panel B. Application score at the listed programs (SD)}}\\"))
application_score_rows = data_rows(between(applications, r"\textit{Panel B. Application score at the listed programs (SD)}}\\",
                                          r"\textit{Panel C. The listed cutoffs}}\\"))
cutoff_rows = data_rows(between(applications, r"\textit{Panel C. The listed cutoffs}}\\", r"\bottomrule"))
assert [len(x) for x in (score_rows, list_rows, application_score_rows, cutoff_rows)] == [6, 8, 14, 4]
app_n = next(line for line in applications.splitlines() if line.startswith("$N$"))
app_n_cells = [x.strip() for x in app_n.removesuffix(r"\\").split("&")]
no_offer_ot, total_ot, no_offer_ever, total_ever = app_n_cells[1:]

# Table VII: application choices among regular-track applicants.
header4 = [
    r"\begin{tabular}{lcccc}", r"\toprule",
    r" & \multicolumn{2}{c}{On time} & \multicolumn{2}{c}{Ever}\\",
    r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
    r" & No offer & 2SLS & No offer & 2SLS\\",
    r" & mean &  & mean & \\", r" & (1) & (2) & (3) & (4)\\",
]
choices = [provenance] + header4 + [r"\midrule"] + list_rows
choices += [r"\midrule", app_n, r"\bottomrule", r"\end{tabular}"]
write("lottery_application_choices.tex", choices)

# Table VIII: individual scores and weighted application scores. Retain N
# columns and identify the applicant sample on each row. Preserve the removed
# cutoff panel as comments, as in the dated manuscript reference.
def with_sample_sizes(rows, labels=None):
    expanded = []
    for i, line in enumerate(rows):
        cells = [x.strip() for x in line.removesuffix(r"\\").split("&")]
        assert len(cells) == 5
        if labels:
            cells[0] = labels.get(cells[0], cells[0])
        n_ot, n_ever = (total_ot, total_ever) if i % 2 == 0 else ("", "")
        expanded.append(" & ".join(cells[:3] + [n_ot] + cells[3:] + [n_ever]) + r"\\")
        expanded_cells = [x.strip() for x in expanded[-1].removesuffix(r"\\").split("&")]
        assert [expanded_cells[j] for j in (0, 1, 2, 4, 5)] == cells
    return expanded


expanded_application_rows = with_sample_sizes(application_score_rows)
expanded_cutoff_rows = with_sample_sizes(cutoff_rows, {
    r"\quad Listed programs whose cutoff is missed (\%)": r"\quad Listed cutoffs missed (\%)",
    r"\quad Reached at least one listed cutoff (\%)": r"\quad Reached a listed cutoff (\%)",
})
header6 = scores.split(r"\midrule", 1)[0].strip().splitlines()
combined_scores = [provenance] + header6
combined_scores += panel("Panel A. Individual admission scores (SD)", score_rows, columns=7)
combined_scores += panel("Panel B. Application score at the listed programs (SD)", expanded_application_rows, columns=7)
combined_scores += ["% " + line for line in
                    panel("Panel C. Cutoff attainment at listed programs", expanded_cutoff_rows, columns=7)]
combined_scores += [r"\bottomrule", r"\end{tabular}"]
write("lottery_admission_scores.tex", combined_scores)


def wrapper(name, caption, label, body, notes, spacing):
    write("results/" + name, [
        provenance, r"\begin{table}[htp!]",
        rf"\singlespacing\renewcommand{{\arraystretch}}{{{spacing}}}",
        r"\centering", rf"\caption{{{{{caption}}}}}\label{{{label}}}",
        r"\small", r"\setlength{\tabcolsep}{6pt}", rf"\input{{tables/{body}}}",
        r"\par\smallskip", r"\begin{minipage}{\textwidth}\footnotesize",
        r"{Notes: " + notes + "}", r"\end{minipage}", r"\end{table}",
    ])


wrapper("lottery_application_choices.tex",
        "Effect of Attending an Over-Demanded School on Application Choices",
        "tab: lottery application choices", "lottery_application_choices.tex",
        r"2SLS estimates with the specification of Table~\ref{tab: lottery college}; means among students without an offer. "
        r"Effects are in program counts, cutoff percentiles, or percentage points as indicated. "
        r"A cutoff percentile ranks the program's cutoff among the process's programs. "
        r"On time and ever are defined in Section~\ref{sec:lottery-data}. "
        r"Heteroskedasticity-robust standard errors in parentheses. $^{***}p<0.01$, $^{**}p<0.05$, $^{*}p<0.1$.",
        spacing="1.2")
wrapper("lottery_admission_scores.tex",
        # The caption and 'Panels B' wording below reproduce the author-edited
        # snapshot exactly. The handoff flags these remaining editorial issues.
        "Effect of Attending an Over-Demanded School on Admission Scores and Cutoff Attainment",
        "tab: lottery scores", "lottery_admission_scores.tex",
        r"2SLS estimates as in Table~\ref{tab: lottery college}; means among students without an offer. "
        r"Panel A uses students with both compulsory exam scores for Math-Verbal, and graduates with both NEM and Ranking for those rows. "
        r"NEM and Ranking are official for 137,487 of the 161,310 students ever, and computed from school records for the rest. "
        r"Panels B uses the applicants and first lists in Table~\ref{tab: lottery application choices}; Panel B averages scores and components over listed programs. "
        r"Panel A is in SD of each score; Panel B is in SD of published application scores. Parts share the total's centering and scale and add to it before rounding. "
        + f"Panels B includes {no_offer_ot} students without an offer on time, {no_offer_ever} ever. "
        + r"Heteroskedasticity-robust standard errors in parentheses. $^{***}p<0.01$, $^{**}p<0.05$, $^{*}p<0.1$.",
        spacing="1.0")
print("Wrote application choices and admission scores; cutoff panel remains commented out; source estimates are unchanged.")
